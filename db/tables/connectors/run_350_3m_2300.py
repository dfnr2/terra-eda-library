#!/usr/bin/env python3
"""3M 2300 series pin strip header: 2303-6111-TG (1 row x 3, 0.100", straight, gold).

Used by the Asteroids adapter's J3 and J4 (the schematic spells it 2303-6111TG). Part
number decoded from the TS-0766-B ordering table (23XX-6XXX-XX): 23 03 = one row, 3 pins;
6 1 11 = pin length 0.230" (5.84 mm), 0.120" (3.05 mm) solder tails; TG = 10 uin gold.

Digi-Key lists this part obsolete (checked via search snippet 2026-11-09; the 3M, Digi-Key
and Mouser pages block automated fetches, so it is not confirmed from 3M). The row is
therefore `Obsolete` and bom_comment points at the nearest Active terra header. Only this
one orderable part is listed; the sheet covers the whole 2300 family.

Stock KiCad symbol and footprint (Connector_PinHeader_2.54mm, 1.0 mm holes against the
sheet's recommended 1.02 mm). Plan: plans/connectors-3m-2300-header.md.
Generated output (dump_priority=0, source=NULL) is not dumped to static SQL.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUTPUT_FILE = HERE / "connectors_generated_350_3m_2300.sql"
CREATED_BY = Path(__file__).name

DATASHEET = "${TERRA_EDA_LIB}/datasheets/3m/ts0766.pdf"

# From TS-0766-B: current, withstanding voltage, insulation resistance, temperature range,
# UL94 V-0 glass-filled insulation, copper-alloy contacts, 0.025" square pin.
FAMILY = {
    "connector_category": "wire-to-board", "connector_family": "3M 2300 pin strip header",
    "connector_series": "2300", "connector_type": "header",
    "rows": 1, "pitch_mm": 2.54, "orientation": "vertical",
    "termination_type": "Through Hole", "gender": "male",
    "polarized": "no", "locking_mechanism": "none", "shielding": "unshielded",
    "color": "black", "current_rating": 3.0, "dielectric_withstand_vrms": 100.0,
    "insulation_resistance_mohm": 5000.0, "signal_type": "signal",
    "flammability_rating": "UL94-V0",
    "mating_family": "0.100in (2.54mm) sockets and female headers, 0.025in square pin",
}

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "value", "description",
    "datasheet", "manufacturer_link", "kicad_symbol", "kicad_footprint",
    "lifecycle_status", "rohs", "allow_substitution", "tracking", "bom_comment",
    "created_by", "source", "dump_priority", "tier", "keywords", "pin_count",
    "temp_operating_min", "temp_operating_max",
    "connector_category", "connector_family", "connector_series", "connector_type",
    "positions", "rows", "pitch_mm", "orientation", "termination_type", "gender",
    "polarized", "locking_mechanism", "shielding", "color",
    "current_rating", "dielectric_withstand_vrms", "insulation_resistance_mohm",
    "signal_type", "flammability_rating", "mating_family",
]


def parts():
    mpn = "2303-6111-TG"
    yield {
        **FAMILY,
        "unique_id": f"3M-{mpn}",
        "part_locator": "conn-header-3pos-2.54mm-1row-th-gold",
        "mpn": mpn, "manufacturer": "3M", "value": mpn,
        "description": (
            "3M 2300 series pin strip header 2303-6111-TG, 2.54mm pitch, 1x03, straight, "
            "through-hole solder tails 3.05mm, 5.84mm pin, 10uin gold"
        ),
        "datasheet": DATASHEET,
        "manufacturer_link": "https://www.3m.com/3M/en_US/p/d/b30000135",
        "kicad_symbol": "Connector_Generic:Conn_01x03",
        "kicad_footprint": "Connector_PinHeader_2.54mm:PinHeader_1x03_P2.54mm_Vertical",
        "lifecycle_status": "Obsolete", "rohs": "No",
        "allow_substitution": "No", "tracking": "No",
        "bom_comment": (
            "Listed obsolete by Digi-Key; not confirmed from 3M. Candidate replacement "
            "(unconfirmed, tin plated, 6.09mm pin): Molex 22-28-4030."
        ),
        "created_by": CREATED_BY, "source": None, "dump_priority": 0, "tier": 2,
        "keywords": ("connector,header,pin-header,3m,2300,2.54mm,0.1in,vertical,gold,"
                     f"3-pin,{mpn},2303-6111TG"),
        "pin_count": "3", "positions": 3,
        "temp_operating_min": -55, "temp_operating_max": 105,
    }


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def insert(p):
    vals = ", ".join(sql(p.get(c)) for c in COLS)
    return f"INSERT INTO connectors ({', '.join(COLS)}) VALUES ({vals});"


def main():
    rows = list(parts())
    ids = [p["unique_id"] for p in rows]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        sys.exit(f"duplicate unique_id: {dupes}")
    lines = [
        "-- Terra EDA Library - 3M 2300 series pin strip headers",
        f"-- Generated by {CREATED_BY}.",
        "-- dump_priority=0, source=NULL: regenerated, not dumped to static SQL.",
        "", "BEGIN TRANSACTION;", "",
        *(insert(p) for p in rows),
        "", "COMMIT;", "",
    ]
    OUTPUT_FILE.write_text("\n".join(lines))
    print(f"Generated {OUTPUT_FILE.name}: {len(rows)} parts")
    if not (ROOT / DATASHEET.replace("${TERRA_EDA_LIB}/", "")).exists():
        print(f"WARNING: datasheet missing: {DATASHEET}")


if __name__ == "__main__":
    main()
