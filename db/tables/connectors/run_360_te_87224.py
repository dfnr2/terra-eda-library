#!/usr/bin/env python3
"""TE Connectivity (AMP) 87224 family: MOD II header, 0.025" square post, single row, 0.100".

All 40 positions on the drawing (ENG_CD_87224_M, rev M 2021-05-07), 87224-1 (1 position)
through 4-87224-0 (40). Part number is `<tens>-87224-<units>` with the tens prefix omitted
below 10 (87224-3 = 3 positions, 1-87224-0 = 10, 4-87224-0 = 40). Not listed: 4-87224-3,
a 3-position part the drawing marks obsolete (single-tube packaging).

The drawing gives geometry and finish only (post lengths, 0.035" hole layout, 15 uin gold
in the contact area over 50 uin nickel, phosphor-bronze post, black thermoplastic
housing). It has no current/voltage/temperature ratings or RoHS statement, so those columns
are left blank. Stock KiCad symbol and footprint (Connector_PinHeader_2.54mm, 1.0 mm holes
against the drawing's 0.89 mm +/-0.08 mm). Plan: plans/connectors-te-87224-header.md.
Generated output (dump_priority=0, source=NULL) is not dumped to static SQL.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUTPUT_FILE = HERE / "connectors_generated_360_te_87224.sql"
CREATED_BY = Path(__file__).name

POSITIONS = range(1, 41)
DATASHEET = "${TERRA_EDA_LIB}/datasheets/te/ENG_CD_87224_M.pdf"

FAMILY = {
    "connector_category": "wire-to-board", "connector_family": "TE MOD II header",
    "connector_series": "87224", "connector_type": "header",
    "rows": 1, "pitch_mm": 2.54, "orientation": "vertical",
    "termination_type": "Through Hole", "gender": "male",
    "polarized": "no", "locking_mechanism": "none", "shielding": "unshielded",
    "color": "black",
    "mating_family": "0.100in (2.54mm) sockets and female headers, 0.025in square post",
}

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "value", "description",
    "datasheet", "manufacturer_link", "kicad_symbol", "kicad_footprint",
    "lifecycle_status", "allow_substitution", "tracking",
    "created_by", "source", "dump_priority", "tier", "keywords", "pin_count",
    "connector_category", "connector_family", "connector_series", "connector_type",
    "positions", "rows", "pitch_mm", "orientation", "termination_type", "gender",
    "polarized", "locking_mechanism", "shielding", "color", "mating_family",
]


def mpn_for(n):
    tens, units = divmod(n, 10)
    return f"{tens}-87224-{units}" if tens else f"87224-{units}"


def parts():
    for n in POSITIONS:
        mpn = mpn_for(n)
        yield {
            **FAMILY,
            "unique_id": f"TE-{mpn}",
            "part_locator": f"conn-header-{n}pos-2.54mm-1row-th-gold",
            "mpn": mpn, "manufacturer": "TE Connectivity", "value": mpn,
            "description": (
                f"TE Connectivity MOD II header {mpn}, 2.54mm pitch, 1x{n:02d}, vertical, "
                "through-hole, 0.025in square post, 8.08mm post above housing, 3.18mm tail, "
                "gold contact area, stackable"
            ),
            "datasheet": DATASHEET,
            "manufacturer_link": "https://www.te.com",
            "kicad_symbol": f"Connector_Generic:Conn_01x{n:02d}",
            "kicad_footprint": f"Connector_PinHeader_2.54mm:PinHeader_1x{n:02d}_P2.54mm_Vertical",
            "lifecycle_status": "Active", "allow_substitution": "No", "tracking": "No",
            "created_by": CREATED_BY, "source": None, "dump_priority": 0, "tier": 2,
            "keywords": (f"connector,header,pin-header,te,amp,mod-ii,87224,2.54mm,0.1in,"
                         f"vertical,gold,stackable,{n}-pin,{mpn}"),
            "pin_count": str(n), "positions": n,
        }


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def insert(p):
    vals = ", ".join(sql(p.get(c)) for c in COLS)
    return f"INSERT INTO connectors ({', '.join(COLS)}) VALUES ({vals});"


def main():
    rows = list(parts())
    ids = [p["unique_id"] for p in rows]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        sys.exit(f"duplicate unique_id: {dupes}")
    lines = [
        "-- Terra EDA Library - TE Connectivity 87224 MOD II single-row headers",
        f"-- Generated by {CREATED_BY}.",
        "-- dump_priority=0, source=NULL: regenerated, not dumped to static SQL.",
        "", "BEGIN TRANSACTION;", "",
        *(insert(p) for p in rows),
        "", "COMMIT;", "",
    ]
    OUTPUT_FILE.write_text("\n".join(lines))
    print(f"Generated {OUTPUT_FILE.name}: {len(rows)} parts")
    if not (ROOT / DATASHEET.replace("${TERRA_EDA_LIB}/", "")).exists():
        print(f"WARNING: datasheet missing: {DATASHEET}")


if __name__ == "__main__":
    main()
