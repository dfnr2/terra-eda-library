"""Shared SQL writer and footprint primitives for the 0.156" (3.96 mm) bus generators.

``run_390_te_mta156_round_post.py`` (TE MTA-156 round-post headers) and
``run_395_molex_kk156_41815.py`` (Molex KK 156 PCB receptacles) both write their own
footprints into ``terra_footprints_connectors``, from the manufacturers' drawings, with
pin 1 at the footprint origin and the row running along +x. KiCad ships neither
family's footprints.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
FP_LIB = "terra_footprints_connectors"
FP_DIR = ROOT / "kicad_footprints" / f"{FP_LIB}.pretty"
PITCH = 3.96

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "value", "description",
    "datasheet", "manufacturer_link", "kicad_symbol", "kicad_footprint",
    "lifecycle_status", "rohs", "allow_substitution", "tracking",
    "created_by", "source", "dump_priority", "tier", "keywords", "pin_count",
    "temp_operating_min", "temp_operating_max",
    "connector_category", "connector_family", "connector_series", "connector_type",
    "positions", "rows", "pitch_mm", "orientation", "termination_type", "gender",
    "polarized", "keying_detail", "locking_mechanism", "shielding", "color",
    "current_rating", "voltage_rating", "signal_type", "flammability_rating",
    "mating_family", "mates_with",
]


# --- SQL ---------------------------------------------------------------------------

def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def write(output_file, title, created_by, rows):
    """Write the INSERTs, failing on a duplicate unique_id rather than dropping rows."""
    ids = [r["unique_id"] for r in rows]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit(f"duplicate unique_id: {dupes}")
    lines = [
        f"-- Terra EDA Library - connectors: {title}",
        f"-- Generated by {created_by}. dump_priority=0, source=NULL: not dumped to static SQL.",
        "",
        "BEGIN TRANSACTION;",
        "",
    ]
    for r in rows:
        vals = ", ".join(sql(r.get(c)) for c in COLS)
        lines.append(f"INSERT INTO connectors ({', '.join(COLS)}) VALUES ({vals});")
    lines += ["", "COMMIT;", ""]
    Path(output_file).write_text("\n".join(lines))
    print(f"Generated {Path(output_file).name}: {len(rows)} parts")


def check_datasheets(paths):
    for p in paths:
        if not (ROOT / p.replace("${TERRA_EDA_LIB}/", "")).exists():
            raise SystemExit(f"datasheet missing: {p}")


# --- footprints --------------------------------------------------------------------

def rect(x0, y0, x1, y1, layer, width):
    pts = [(x0, y0), (x1, y0), (x1, y1), (x0, y1), (x0, y0)]
    return "".join(
        f'  (fp_line (start {a[0]:.3f} {a[1]:.3f}) (end {b[0]:.3f} {b[1]:.3f}) '
        f'(layer "{layer}") (width {width}))\n' for a, b in zip(pts, pts[1:]))


def line(x0, y0, x1, y1, layer, width):
    return (f'  (fp_line (start {x0:.3f} {y0:.3f}) (end {x1:.3f} {y1:.3f}) '
            f'(layer "{layer}") (width {width}))\n')


def tht_pad(num, x, y, size, drill, first=False):
    shape = "rect" if first else "circle"
    return (f'  (pad "{num}" thru_hole {shape} (at {x:.3f} {y:.3f}) (size {size} {size}) '
            f'(drill {drill}) (layers *.Cu *.Mask))\n')


def npth(x, y, drill):
    return (f'  (pad "" np_thru_hole circle (at {x:.3f} {y:.3f}) (size {drill} {drill}) '
            f'(drill {drill}) (layers *.Cu *.Mask))\n')


def footprint(name, descr, tags, n, *, pad_size, drill, body, courtyard,
              extra="", npth_offset_y=None, npth_drill=None):
    """One-row THT footprint, pin 1 (square pad) at the origin, pins along +x.

    body / courtyard: (x0, y0, x1, y1) in mm. extra: additional fab/silk primitives.
    npth_offset_y / npth_drill: a second row of non-plated holes (bottom-entry pin
    pass-through) at this y offset under every pin.
    """
    bx0, by0, bx1, by1 = body
    cx0, cy0, cx1, cy1 = courtyard
    mid = (n - 1) * PITCH / 2
    pads = "".join(tht_pad(i + 1, i * PITCH, 0, pad_size, drill, first=(i == 0))
                   for i in range(n))
    if npth_offset_y is not None:
        pads += "".join(npth(i * PITCH, npth_offset_y, npth_drill) for i in range(n))
    s = 0.12
    # pin-1 marker: a short silk tick left of the body, level with pad 1
    marker = line(bx0 - s - 0.6, 0, bx0 - s - 0.1, 0, "F.SilkS", 0.12)
    return (
        f'(footprint "{name}" (version 20211014) (generator terra)\n'
        f'  (layer "F.Cu")\n'
        f'  (descr "{descr}")\n'
        f'  (tags "{tags}")\n'
        f'  (attr through_hole)\n'
        f'  (fp_text reference "REF**" (at {mid:.3f} {cy0 - 1.0:.3f}) (layer "F.SilkS")\n'
        f'    (effects (font (size 1 1) (thickness 0.15)))\n  )\n'
        f'  (fp_text value "{name}" (at {mid:.3f} {cy1 + 1.0:.3f}) (layer "F.Fab")\n'
        f'    (effects (font (size 1 1) (thickness 0.15)))\n  )\n'
        f'  (fp_text user "${{REFERENCE}}" (at {mid:.3f} {(by0 + by1) / 2:.3f}) (layer "F.Fab")\n'
        f'    (effects (font (size 1 1) (thickness 0.15)))\n  )\n'
        + rect(bx0, by0, bx1, by1, "F.Fab", 0.1)
        + rect(bx0 - s, by0 - s, bx1 + s, by1 + s, "F.SilkS", 0.12)
        + marker
        + rect(cx0, cy0, cx1, cy1, "F.CrtYd", 0.05)
        + extra + pads + ")\n")


def write_footprint(name, text):
    FP_DIR.mkdir(parents=True, exist_ok=True)
    (FP_DIR / f"{name}.kicad_mod").write_text(text)
