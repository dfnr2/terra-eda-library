#!/usr/bin/env python3
"""Molex KK 254 breakaway pin headers (series 42375): 2.54 mm, single row, vertical.

Molex 22-28-4NNx, NN = circuits (2-36), x = plating / mating-pin variant. These are
plain 0.64 mm square-post headers, so they use KiCad's stock pin-header footprint
(which ships with a 3D model) and stock Connector_Generic symbols.

Plan and parameter sources: plans/connectors-molex-kk254-breakaway.md.
Generated output (dump_priority=0, source=NULL) is not dumped to static SQL.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUTPUT_FILE = HERE / "connectors_generated_330_molex_kk254_breakaway.sql"
CREATED_BY = Path(__file__).name

CIRCUITS = range(2, 37)

# Last digit of the Molex part number. 1 and 4 (8.13 mm mating pin) and 5-8 (0.76 um
# gold, other tails) exist for some counts but are unverified across the range.
VARIANTS = {
    "0": {"plating": "tin", "text": "tin plating", "mating_pin": "6.09mm"},
    "3": {"plating": "gold", "text": "0.38um gold selective plating", "mating_pin": "6.09mm"},
}
ENABLED_VARIANTS = ("0", "3")

DATASHEET = "${TERRA_EDA_LIB}/datasheets/molex/kk-254-42375-breakaway-header.pdf"

# Family-wide, from the Molex part sheet for 22-28-4040 (series 42375). Operating
# temperature is left blank: the sheet defers to product spec PS-10-07-001.
FAMILY = {
    "connector_category": "wire-to-board", "connector_family": "Molex KK 254",
    "connector_series": "42375", "connector_type": "header",
    "rows": 1, "pitch_mm": 2.54, "orientation": "vertical",
    "termination_type": "Through Hole", "gender": "male",
    "polarized": "no", "locking_mechanism": "none", "shielding": "unshielded",
    "color": "black", "current_rating": 4.0, "voltage_rating": 500.0,
    "signal_type": "signal", "flammability_rating": "UL94-V0",
    "mating_family": "Molex KK 254 crimp housings (2695, 6471, 7880), KK PC board connector 4455",
}

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "value", "description",
    "datasheet", "manufacturer_link", "kicad_symbol", "kicad_footprint",
    "lifecycle_status", "rohs", "allow_substitution", "tracking",
    "created_by", "source", "dump_priority", "tier", "keywords", "pin_count",
    "connector_category", "connector_family", "connector_series", "connector_type",
    "positions", "rows", "pitch_mm", "orientation", "termination_type", "gender",
    "polarized", "locking_mechanism", "shielding", "color",
    "current_rating", "voltage_rating", "signal_type", "flammability_rating",
    "mating_family",
]


def parts():
    """One dict per orderable header, in variant then circuit order."""
    for x in ENABLED_VARIANTS:
        v = VARIANTS[x]
        for n in CIRCUITS:
            pn = f"22-28-4{n:02d}{x}"   # Molex's printed part number
            mpn = pn.replace("-", "")   # Molex's catalog number
            yield {
                **FAMILY,
                "unique_id": f"Molex-{mpn}",
                "part_locator": f"conn-header-{n}pos-42375-{v['plating']}",
                "mpn": mpn, "manufacturer": "Molex", "value": pn,
                "description": (
                    f"Molex KK 254 {pn} breakaway pin header, 2.54mm pitch, 1x{n:02d}, "
                    f"vertical, through-hole, {v['text']}, {v['mating_pin']} mating pin"
                ),
                "datasheet": DATASHEET,
                "manufacturer_link": f"https://www.molex.com/en-us/products/part-detail/{mpn}",
                "kicad_symbol": f"Connector_Generic:Conn_01x{n:02d}",
                "kicad_footprint": (
                    f"Connector_PinHeader_2.54mm:PinHeader_1x{n:02d}_P2.54mm_Vertical"
                ),
                "lifecycle_status": "Active", "rohs": "Yes",
                "allow_substitution": "No", "tracking": "No",
                "created_by": CREATED_BY, "source": None, "dump_priority": 0, "tier": 2,
                "keywords": (
                    f"connector,header,pin-header,molex,kk254,breakaway,2.54mm,0.1in,"
                    f"vertical,{v['plating']},{pn},{mpn}"
                ),
                "pin_count": str(n), "positions": n,
            }


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def insert(p):
    vals = ", ".join(sql(p[c]) for c in COLS)
    return f"INSERT INTO connectors ({', '.join(COLS)}) VALUES ({vals});"


def main():
    rows = list(parts())
    ids = [p["unique_id"] for p in rows]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        sys.exit(f"duplicate unique_id: {dupes}")
    lines = [
        "-- Terra EDA Library - Molex KK 254 breakaway pin headers (series 42375), vertical",
        f"-- Generated by {CREATED_BY}.",
        "-- dump_priority=0, source=NULL: regenerated, not dumped to static SQL.",
        "",
        "BEGIN TRANSACTION;",
        "",
        *(insert(p) for p in rows),
        "",
        "COMMIT;",
        "",
    ]
    OUTPUT_FILE.write_text("\n".join(lines))
    print(f"Generated {OUTPUT_FILE.name}: {len(rows)} parts")
    if not (ROOT / DATASHEET.replace("${TERRA_EDA_LIB}/", "")).exists():
        print(f"WARNING: datasheet missing: {DATASHEET}")


if __name__ == "__main__":
    main()
