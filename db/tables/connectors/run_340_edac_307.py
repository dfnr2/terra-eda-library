#!/usr/bin/env python3
"""EDAC 307 series 0.156" card-edge connector: 307-044-558-202 (44 contacts, 2x22).

Used by the Asteroids adapter's J1 (the cabinet-harness side). The footprint and its
STEP come from that project's EDAC footprint; the symbol names pins by edge position
(1-22 on one side, A-Z without G/I/O/Q on the other), matching the pad names.

Only the one orderable part is listed. The 307/357 drawing covers the whole series
(contact codes, mounting codes); other counts/codes are added by extending PARTS from
that drawing. Plan: plans/connectors-edac-307-card-edge.md.
Generated output (dump_priority=0, source=NULL) is not dumped to static SQL.
Each part also has a per-pin symbol row (`-pins`, Conn_PerPin_EdgeLetter_2x22, _connkit.py).
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from _connkit import edge_letter_pins_id, edge_letter_pins_symbol, with_pins, write_symbols  # noqa: E402
ROOT = HERE.parents[2]
OUTPUT_FILE = HERE / "connectors_generated_340_edac_307.sql"
CREATED_BY = Path(__file__).name

DATASHEET = "${TERRA_EDA_LIB}/datasheets/edac/307-044-558-202-card-edge-connector.pdf"
SYMBOL = "terra_symbols_connectors:EDAC_Card_Edge_2x22_P3.96mm"
FOOTPRINT = "terra_footprints_connectors:EDAC_307-044-558-202_2x22_P3.96mm"

# Geometry is from the EDAC 307/357 drawing (3.96 mm contact spacing, 5.08 mm row
# spacing, card slot for 1.37-1.78 mm boards). Current, withstand voltage and
# temperature range are NOT on the drawing; they are from the Heilind listing.
# orientation is left blank: the drawing's 90-degree bend applies to contact codes 522
# and 540 only, and this part is code 558, but Heilind lists it as right angle.
FAMILY = {
    "connector_category": "board-to-board", "connector_family": "EDAC 307 card edge",
    "connector_series": "307", "connector_type": "receptacle",
    "rows": 2, "pitch_mm": 3.96, "row_pitch_mm": 5.08,
    "termination_type": "Through Hole", "gender": "female",
    "polarized": "no", "locking_mechanism": "none", "shielding": "unshielded",
    "current_rating": 5.0, "dielectric_withstand_vrms": 1800.0,
    "signal_type": "mixed",
}

COLS = [
    "unique_id", "variant", "part_locator", "mpn", "manufacturer", "value", "description",
    "datasheet", "manufacturer_link", "kicad_symbol", "kicad_footprint",
    "lifecycle_status", "rohs", "allow_substitution", "tracking",
    "created_by", "source", "dump_priority", "tier", "keywords", "pin_count",
    "connector_category", "connector_family", "connector_series", "connector_type",
    "positions", "rows", "pitch_mm", "row_pitch_mm", "termination_type", "gender",
    "polarized", "locking_mechanism", "shielding",
    "current_rating", "dielectric_withstand_vrms", "signal_type", "mating_family",
]


def parts():
    mpn = "307-044-558-202"
    yield {
        **FAMILY,
        "unique_id": f"EDAC-{mpn}",
        "part_locator": "conn-card-edge-44pos-3.96mm-2row-th",
        "mpn": mpn, "manufacturer": "EDAC", "value": mpn,
        "description": (
            "EDAC 307 series card-edge receptacle 307-044-558-202, 44 contacts (2x22), "
            "0.156in (3.96mm) contact spacing, 0.200in row spacing, through-hole, "
            "dual-row contact code 558, mounting code 202 (floating eyelets), "
            "for 0.054-0.070in PCBs"
        ),
        "datasheet": DATASHEET,
        "manufacturer_link": "https://www.edac.net",
        "kicad_symbol": SYMBOL, "kicad_footprint": FOOTPRINT,
        "lifecycle_status": "Active", "rohs": "Yes",
        "allow_substitution": "No", "tracking": "No",
        "created_by": CREATED_BY, "source": None, "dump_priority": 0, "tier": 2,
        "keywords": (
            "connector,card-edge,edge-connector,edac,307,0.156in,3.96mm,44-pin,"
            f"2x22,through-hole,{mpn}"
        ),
        "pin_count": "44", "positions": 44,
        "mating_family": "0.062in (1.57mm) PCB edge fingers on 0.156in centres",
    }


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def insert(p):
    vals = ", ".join(sql(p.get(c)) for c in COLS)
    return f"INSERT INTO connectors ({', '.join(COLS)}) VALUES ({vals});"


def main():
    write_symbols([edge_letter_pins_symbol(22)])
    rows = with_pins(list(parts()), lambda r: edge_letter_pins_id(22))
    ids = [p["unique_id"] for p in rows]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        sys.exit(f"duplicate unique_id: {dupes}")
    lines = [
        "-- Terra EDA Library - EDAC 307 series 0.156in card-edge connectors",
        f"-- Generated by {CREATED_BY}.",
        "-- dump_priority=0, source=NULL: regenerated, not dumped to static SQL.",
        "",
        "BEGIN TRANSACTION;",
        "",
        *(insert(p) for p in rows),
        "",
        "COMMIT;",
        "",
    ]
    OUTPUT_FILE.write_text("\n".join(lines))
    print(f"Generated {OUTPUT_FILE.name}: {len(rows)} parts")
    if not (ROOT / DATASHEET.replace("${TERRA_EDA_LIB}/", "")).exists():
        print(f"WARNING: datasheet missing: {DATASHEET}")


if __name__ == "__main__":
    main()
