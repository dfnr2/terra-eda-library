"""Shared emit helpers for the through-hole mosfet generators (run_330, run_340).

Each generator builds part dicts (keys = a subset of COLS; missing keys become
NULL) and calls write(). Every part carries `pinout`, the datasheet's lead order
for pins 1-2-3 (e.g. "GDS"); write() refuses a row whose kicad_symbol numbers its
pins differently, so a symbol is never borrowed across pinouts.

Output is dump_priority=0 / source=NULL: generated, never dumped to static SQL.
"""
from pathlib import Path

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "package", "value",
    "description", "datasheet", "manufacturer_link", "kicad_symbol",
    "kicad_footprint", "lifecycle_status", "allow_substitution", "tracking",
    "created_by", "source", "dump_priority", "tier", "keywords", "pin_count",
    "temp_operating_min", "temp_operating_max", "temp_storage_min", "temp_storage_max",
    "temp_soldering", "transistor_type", "channels", "v_ce_ds_max", "i_c_d_max",
    "power_dissipation", "rds_on", "vgs_th", "temp_junction_max",
]

# Pin 1-2-3 function of each stock KiCad 10 Transistor_FET symbol used here,
# transcribed from /usr/share/kicad/symbols/Transistor_FET.kicad_sym (resolving
# `extends`): e.g. IRF540N extends BUZ11 = 1 G, 2 D, 3 S.
SYMBOL_PINS = {
    "Transistor_FET:2N7000": "SGD",
    "Transistor_FET:BS170": "DGS",
    "Transistor_FET:BS250": "DGS",
    "Transistor_FET:IRF540N": "GDS",
    "Transistor_FET:IRF9540N": "GDS",
    "Transistor_FET:IRLZ44N": "GDS",
    "Transistor_FET:IRF3205": "GDS",
    "Transistor_FET:IRF4905": "GDS",
    "Transistor_FET:IRLB8721PBF": "GDS",
    "Transistor_FET:IRF740": "GDS",
    "Transistor_FET:FQP27P06": "GDS",
    "Transistor_FET:Q_NMOS_GDS": "GDS",
    "Transistor_FET:Q_PMOS_GDS": "GDS",
}

# Polarity each stock symbol draws, so an N-channel part never lands on a P symbol.
SYMBOL_TYPE = {
    "Transistor_FET:BS250": "pmos",
    "Transistor_FET:IRF9540N": "pmos",
    "Transistor_FET:IRF4905": "pmos",
    "Transistor_FET:FQP27P06": "pmos",
    "Transistor_FET:Q_PMOS_GDS": "pmos",
}


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def check(parts):
    """Fail loudly on duplicate ids, unknown symbols, or pinout/polarity mismatches."""
    ids = [p["unique_id"] for p in parts]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit(f"duplicate unique_id: {dupes}")
    for p in parts:
        sym = p["kicad_symbol"]
        if sym not in SYMBOL_PINS:
            raise SystemExit(f"{p['mpn']}: symbol {sym} has no recorded pin map")
        if SYMBOL_PINS[sym] != p["pinout"]:
            raise SystemExit(f"{p['mpn']}: datasheet pinout {p['pinout']} != "
                             f"{sym} pins {SYMBOL_PINS[sym]}")
        if SYMBOL_TYPE.get(sym, "nmos") != p["transistor_type"]:
            raise SystemExit(f"{p['mpn']}: {p['transistor_type']} on {sym}")


def write(output_file, created_by, parts, title):
    check(parts)
    rows = [
        f"INSERT INTO mosfet ({', '.join(COLS)}) VALUES "
        f"({', '.join(sql(p.get(c)) for c in COLS)});"
        for p in parts
    ]
    lines = [
        f"-- Terra EDA Library - {title}",
        f"-- Generated by {created_by}.",
        "-- dump_priority=0, source=NULL: regenerated, not dumped to static SQL.",
        "", "BEGIN TRANSACTION;", "", *rows, "", "COMMIT;", "",
    ]
    Path(output_file).write_text("\n".join(lines))
    print(f"Generated {Path(output_file).name}: {len(rows)} parts")
    for p in parts:
        if p.get("lifecycle_status") != "Active":
            print(f"  note: {p['mpn']} lifecycle {p['lifecycle_status']}")
    return len(rows)
