#!/usr/bin/env python3
"""Diodes Inc. DMP3056L P-channel MOSFET, 30V, SOT-23.

Specs are transcribed from datasheets/diodes-inc/DMP3056L.pdf (DS37386 Rev. 6-2, June 2021).
Pinning is the standard SOT-23 1 = G, 2 = S, 3 = D, so the stock KiCad symbol
Transistor_FET:BSS84 (same pin order) is used with Package_TO_SOT_SMD:SOT-23.

mpn is the type number; the datasheet orders it as DMP3056L-7 (3000/reel) and
DMP3056L-13 (10000/reel), which are not recorded here. unique_id uses the same
"Diodes, Inc." manufacturer string as the existing DMP3099L row.
Lifecycle: the Diodes product page returned 403 when checked (2026-11-15), so Active is
assumed from the current datasheet and should be rechecked against a distributor.
No soldering peak temperature is given, so temp_soldering is NULL.

Generated output (dump_priority=0, source=NULL) is not dumped to static SQL.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUTPUT_FILE = HERE / "mosfet_generated_320_diodes_dmp.sql"
CREATED_BY = Path(__file__).name

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "package", "value",
    "description", "datasheet", "manufacturer_link", "kicad_symbol",
    "kicad_footprint", "lifecycle_status", "rohs", "allow_substitution", "tracking",
    "created_by", "source", "dump_priority", "tier", "keywords", "pin_count",
    "temp_operating_min", "temp_operating_max", "temp_storage_min", "temp_storage_max",
    "transistor_type", "channels", "v_ce_ds_max", "i_c_d_max", "power_dissipation",
    "rds_on", "vgs_th", "temp_junction_max",
]

COMMON = {
    "manufacturer": "Diodes, Inc.", "package": "SOT-23",
    "kicad_footprint": "Package_TO_SOT_SMD:SOT-23",
    "lifecycle_status": "Active", "rohs": "Yes", "allow_substitution": "No", "tracking": "No",
    "created_by": CREATED_BY, "source": None, "dump_priority": 0, "tier": 2,
    "pin_count": "3", "channels": 1,
    "temp_operating_min": -55, "temp_operating_max": 150,
    "temp_storage_min": -55, "temp_storage_max": 150, "temp_junction_max": "150C",
}

PARTS = [
    {
        **COMMON,
        "unique_id": "Diodes, Inc.-DMP3056L", "mpn": "DMP3056L", "value": "DMP3056L",
        "part_locator": "mosfet-pch-30v-4.3a-sot23",
        "description": ("Diodes Inc. DMP3056L P-channel enhancement MOSFET, -30V -4.3A, "
                        "RDS(on) 50 mOhm max @ -10V, SOT-23"),
        "datasheet": "${TERRA_EDA_LIB}/datasheets/diodes-inc/DMP3056L.pdf",
        "manufacturer_link": "https://www.diodes.com/part/view/DMP3056L",
        "kicad_symbol": "Transistor_FET:BSS84",
        "keywords": "mosfet,transistor,p-channel,pmos,high-side,load-switch,sot-23,30V,DMP3056L",
        "transistor_type": "pmos", "v_ce_ds_max": "30V", "i_c_d_max": "4.3A",
        "power_dissipation": "1.38W (Ta=25C)",
        "rds_on": "50mOhm max @ Vgs=-10V, Id=-6A (70mOhm max @ Vgs=-4.5V, Id=-5A)",
        "vgs_th": "-1.0V min / -2.1V max",
    },
]


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    ids = [p["unique_id"] for p in PARTS]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit(f"duplicate unique_id: {dupes}")
    lines = [
        "-- Terra EDA Library - Diodes Inc. DMP3056L P-channel MOSFET",
        f"-- Generated by {CREATED_BY}.",
        "-- dump_priority=0, source=NULL: regenerated, not dumped to static SQL.",
        "", "BEGIN TRANSACTION;", "",
    ]
    for p in PARTS:
        vals = ", ".join(sql(p.get(c)) for c in COLS)
        lines.append(f"INSERT INTO mosfet ({', '.join(COLS)}) VALUES ({vals});")
    lines += ["", "COMMIT;", ""]
    OUTPUT_FILE.write_text("\n".join(lines))
    print(f"Generated {OUTPUT_FILE.name}: {len(PARTS)} parts")


if __name__ == "__main__":
    main()
