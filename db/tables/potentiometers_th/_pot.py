"""Shared row builder and SQL writer for the potentiometers_th generators.

Each ``run_3x0_*.py`` script lists one trimmer family's pin styles and the codes of
its datasheet's standard resistance table, then calls ``row()`` once per orderable
code and ``write()``. tolerance/power_rating/temp_coeff/composition use the
resistors_th formats (``±10%``, ``1/2W``, ``±100ppm/°C``, ``Cermet``); value is the
end-to-end resistance with its unit sign (``10kΩ``).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "tools"))
from passive_units import unit_value  # noqa: E402

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "package", "value",
    "description", "datasheet", "manufacturer_link", "kicad_symbol", "kicad_footprint",
    "lifecycle_status", "rohs", "allow_substitution", "tracking", "standards_version",
    "created_by", "source", "dump_priority", "tier", "keywords", "pin_count",
    "temp_operating_min", "temp_operating_max",
    "tolerance", "power_rating", "temp_coeff", "composition", "turns", "adjustment",
]

DS_ROOT = "${TERRA_EDA_LIB}/datasheets"
SYMBOL = "Device:R_Potentiometer_Trim"

# Bourns standard resistance table (3296 and 3362 sheets): code -> ohms.
BOURNS_CODES = {
    "100": 10, "200": 20, "500": 50, "101": 100, "201": 200, "501": 500,
    "102": 1e3, "202": 2e3, "502": 5e3, "103": 10e3, "203": 20e3, "253": 25e3,
    "503": 50e3, "104": 100e3, "204": 200e3, "254": 250e3, "504": 500e3,
    "105": 1e6, "205": 2e6,
}


def ohms_text(ohms):
    """10 -> '10', 25000 -> '25k', 2e6 -> '2M' (input to passive_units)."""
    for div, suffix in ((1e6, "M"), (1e3, "k"), (1, "")):
        if ohms >= div:
            return f"{ohms / div:g}{suffix}"
    raise ValueError(ohms)


def row(*, created_by, manufacturer, series, style, mpn, ohms, tolerance, power,
        temp_coeff, composition, turns, adjustment, temp, package, footprint,
        datasheet, mfr_link=None):
    value = unit_value(ohms_text(ohms), "Ω")
    turn_word = "single-turn" if turns == 1 else f"{turns}-turn"
    multi = "single-turn" if turns == 1 else "multiturn"
    return {
        "unique_id": f"{manufacturer}-{mpn}",
        "part_locator": (f"trimpot-{ohms_text(ohms).lower()}-{turns}turn-{adjustment}"
                         f"-{style.lower()}"),
        "mpn": mpn, "manufacturer": manufacturer, "package": package, "value": value,
        "description": (f"Trimpot {manufacturer} {style} {value} {tolerance} {power} "
                        f"{turn_word} {adjustment}-adjust {composition.lower()}"),
        "datasheet": f"{DS_ROOT}/{datasheet}", "manufacturer_link": mfr_link,
        "kicad_symbol": SYMBOL, "kicad_footprint": footprint,
        "lifecycle_status": "Active", "rohs": "Yes",
        "allow_substitution": "No", "tracking": "No", "standards_version": "1.0",
        "created_by": created_by, "source": None, "dump_priority": 0, "tier": 2,
        "keywords": ", ".join(dict.fromkeys([
            value, "trimpot", "trimmer", "potentiometer", "trim pot", composition.lower(),
            multi, f"{adjustment} adjust", manufacturer, series, style, "through-hole"])),
        "pin_count": "3",
        "temp_operating_min": temp[0], "temp_operating_max": temp[1],
        "tolerance": tolerance, "power_rating": power, "temp_coeff": temp_coeff,
        "composition": composition, "turns": turns, "adjustment": adjustment,
    }


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def write(output_file, title, created_by, recs):
    """Write the INSERTs, failing on a duplicate unique_id rather than dropping rows."""
    ids = [r["unique_id"] for r in recs]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit(f"duplicate unique_id: {dupes}")
    lines = [
        f"-- Terra EDA Library - potentiometers_th {title}",
        f"-- Generated by {created_by}. dump_priority=0, source=NULL: not dumped to static SQL.",
        "",
        "BEGIN TRANSACTION;",
        "",
    ]
    for r in recs:
        vals = ", ".join(sql(r.get(c)) for c in COLS)
        lines.append(f"INSERT INTO potentiometers_th ({', '.join(COLS)}) VALUES ({vals});")
    lines += ["", "COMMIT;", ""]
    Path(output_file).write_text("\n".join(lines))
    print(f"Generated {Path(output_file).name}: {len(recs)} parts")
