#!/usr/bin/env python3
"""NXP PCA9632 4-bit Fm+ I2C low-power LED driver, all three packages.

Source: PCA9632 product data sheet, Rev. 6 (21 September 2021), datasheets/nxp/pca9632.pdf.

The PCA9632 is a PWM switch, not a current regulator: each LEDn pin sinks up to 25 mA
(sources 10 mA in totem-pole mode) and the LED current is set by an external resistor.
driver_topology is therefore 'switch'. The 8-pin parts have a fixed address (0x62); the
TSSOP10 adds A0/A1 for 0x60-0x63.

MPNs are NXP type numbers (Table 1). Orderable codes: PCA9632DP1,118, PCA9632DP2Z
(the DP2,118 reel was discontinued by DN 202104010; DP2Z itself was withdrawn by DN
202507021 and reactivated by RN 202606037, July 2026) and PCA9632TK,118.

Footprint note: PCA9632TK (SOT908-1, exposed pad 1.5 x 2.1 mm nominal, 1.65 x 2.25 max)
uses the stock LT "DD" DFN-8 3x3 land pattern (EP pad 1.66 x 2.38 mm) -- same body,
pitch and lead geometry; the EP land is slightly larger than NXP's pad. Swap in an
exact SOT908-1 footprint here if one is made.

Generated output (dump_priority=0) is not dumped back to static SQL.
"""
from pathlib import Path

OUTPUT_FILE = Path(__file__).with_name("led_drivers_generated_310_nxp_pca9632.sql")

MFR = "NXP"
DS = "${TERRA_EDA_LIB}/datasheets/nxp/pca9632.pdf"
LINK = ("https://www.nxp.com/products/power-management/lighting-driver-and-controller-ics/"
        "led-controllers/4-bit-fm-plus-ic-bus-low-power-led-driver:PCA9632")
SYMLIB = "terra_symbols_led_drivers"

# mpn, package, pin_count, footprint, I2C address note
PARTS = [
    ("PCA9632DP1", "TSSOP-8", "8", "Package_SO:TSSOP-8_3x3mm_P0.65mm",
     "fixed address 0x62"),
    ("PCA9632DP2", "TSSOP-10", "10", "Package_SO:TSSOP-10_3x3mm_P0.5mm",
     "address 0x60-0x63 via A0/A1"),
    ("PCA9632TK", "HVSON-8", "9", "Package_DFN_QFN:DFN-8-1EP_3x3mm_P0.5mm_EP1.66x2.38mm",
     "fixed address 0x62"),
]

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "package", "value",
    "description", "datasheet", "manufacturer_link", "kicad_symbol",
    "kicad_footprint", "lifecycle_status", "rohs", "allow_substitution", "tracking",
    "source", "dump_priority", "tier", "pin_count", "keywords",
    "temp_operating_min", "temp_operating_max", "temp_storage_min",
    "temp_storage_max", "driver_topology", "channels", "output_current",
    "supply_voltage_min", "supply_voltage_max", "output_voltage_max",
    "switching_freq", "dimming_method", "interface", "current_accuracy",
]


def records():
    for mpn, package, pins, footprint, addr in PARTS:
        pkg_slug = package.lower().replace("-", "")
        yield {
            "unique_id": f"{MFR}-{mpn}",
            "part_locator": f"led-driver-i2c-4ch-25ma-pwm-{pkg_slug}",
            "mpn": mpn, "manufacturer": MFR, "package": package, "value": mpn,
            "description": (
                f"NXP PCA9632 4-channel Fm+ I2C low-power LED driver, 8-bit PWM, "
                f"25 mA sink / 10 mA source per output, 2.3-5.5V, {addr}, {package}"
            ),
            "datasheet": DS, "manufacturer_link": LINK,
            "kicad_symbol": f"{SYMLIB}:{mpn}", "kicad_footprint": footprint,
            "lifecycle_status": "Active", "rohs": "Yes",
            "allow_substitution": "No", "tracking": "No",
            "source": None, "dump_priority": 0, "tier": 2, "pin_count": pins,
            "keywords": "LED driver, I2C, Fm+, PWM, RGB, RGBA, dimming, blinking, PCA9632",
            "temp_operating_min": -40, "temp_operating_max": 85,
            "temp_storage_min": -65, "temp_storage_max": 150,
            "driver_topology": "switch", "channels": 4, "output_current": "25mA",
            "supply_voltage_min": 2.3, "supply_voltage_max": 5.5,
            "output_voltage_max": "5.5V", "switching_freq": "1.5625kHz",
            "dimming_method": "pwm", "interface": "i2c", "current_accuracy": None,
        }


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    recs = list(records())
    ids = [r["unique_id"] for r in recs]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit(f"duplicate unique_id: {dupes}")
    lines = [
        "-- Terra EDA Library - led_drivers NXP PCA9632 I2C LED driver",
        f"-- Generated by {Path(__file__).name}. dump_priority=0, source=NULL: not dumped to static SQL.",
        "",
        "BEGIN TRANSACTION;",
        "",
    ]
    for r in recs:
        vals = ", ".join(sql(r.get(c)) for c in COLS)
        lines.append(f"INSERT INTO led_drivers ({', '.join(COLS)}) VALUES ({vals});")
    lines += ["", "COMMIT;", ""]
    OUTPUT_FILE.write_text("\n".join(lines))
    print(f"Generated {OUTPUT_FILE.name}: {len(recs)} parts")


if __name__ == "__main__":
    main()
