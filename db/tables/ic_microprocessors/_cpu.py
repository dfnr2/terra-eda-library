"""Shared row builder and SQL writer for the ic_microprocessors family generators.

Each ``run_3x0_*.py`` script transcribes one family's data sheets and calls ``row()``
once per ordering code, then ``write()``. The column list and defaults live here so
the 6502, 6800, 68000, Z80, Intel, 1802 and TMS9900 families stay consistent.
"""
from pathlib import Path

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "package", "value",
    "description", "datasheet", "manufacturer_link", "kicad_symbol", "kicad_footprint",
    "lifecycle_status", "rohs", "allow_substitution", "tracking", "standards_version",
    "created_by", "source", "dump_priority", "tier", "keywords", "pin_count",
    "temp_operating_min", "temp_operating_max",
    "family", "core", "technology", "architecture_bits", "data_bus_bits",
    "address_bus_bits", "max_clock", "clock_source", "supply_voltage_min",
    "supply_voltage_max", "supply_rails", "active_current", "special_features",
]

DS_ROOT = "${TERRA_EDA_LIB}/datasheets"
LIB = "terra_symbols_ic_microprocessors"

# clock_source values
ON_CHIP = "on-chip oscillator"
EXT_1PH = "external single-phase"
EXT_2PH = "external two-phase"
EXT_4PH = "external four-phase"


def footprint(pins, width_in):
    """Stock DIP land pattern for the row spacing the package outline gives."""
    mm = {0.6: "15.24", 0.9: "22.86"}[width_in]
    return f"Package_DIP:DIP-{pins}_W{mm}mm"


def mhz(clock):
    """2.5 -> '2.5MHz', 4.0 -> '4MHz' (the ic_microcontrollers max_clock format)."""
    return f"{clock:g}MHz"


def row(*, created_by, manufacturer, mpn, value, family, core, technology, arch_bits,
        data_bits, addr_bits, clock, clock_source, vmin, vmax, rails, package, pins,
        symbol, datasheet, description, keywords, features, active_current=None,
        width_in=0.6, lifecycle="Obsolete", rohs="No", mfr_link=None, temp=(0, 70)):
    return {
        "unique_id": f"{manufacturer}-{mpn}",
        "part_locator": f"cpu-{value.lower()}-{mhz(clock).lower()}-dip{pins}",
        "mpn": mpn, "manufacturer": manufacturer, "package": package, "value": value,
        "description": description,
        "datasheet": f"{DS_ROOT}/{datasheet}", "manufacturer_link": mfr_link,
        "kicad_symbol": symbol, "kicad_footprint": footprint(pins, width_in),
        "lifecycle_status": lifecycle, "rohs": rohs,
        "allow_substitution": "No", "tracking": "No", "standards_version": "1.0",
        "created_by": created_by, "source": None, "dump_priority": 0, "tier": 2,
        "keywords": ", ".join(dict.fromkeys([value] + keywords + ["cpu", "microprocessor"])),
        "pin_count": str(pins),
        "temp_operating_min": temp[0], "temp_operating_max": temp[1],
        "family": family, "core": core, "technology": technology,
        "architecture_bits": arch_bits, "data_bus_bits": data_bits,
        "address_bus_bits": addr_bits, "max_clock": mhz(clock),
        "clock_source": clock_source, "supply_voltage_min": vmin,
        "supply_voltage_max": vmax, "supply_rails": rails,
        "active_current": active_current, "special_features": features,
    }


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def write(output_file, title, created_by, recs):
    """Write the INSERTs, failing on a duplicate unique_id rather than dropping rows."""
    ids = [r["unique_id"] for r in recs]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit(f"duplicate unique_id: {dupes}")
    lines = [
        f"-- Terra EDA Library - ic_microprocessors {title}",
        f"-- Generated by {created_by}. dump_priority=0, source=NULL: not dumped to static SQL.",
        "",
        "BEGIN TRANSACTION;",
        "",
    ]
    for r in recs:
        vals = ", ".join(sql(r.get(c)) for c in COLS)
        lines.append(f"INSERT INTO ic_microprocessors ({', '.join(COLS)}) VALUES ({vals});")
    lines += ["", "COMMIT;", ""]
    Path(output_file).write_text("\n".join(lines))
    print(f"Generated {Path(output_file).name}: {len(recs)} parts")
