def generate_resistors() -> str:
    """Generate all current-sense resistor SQL statements."""
    script_name = get_script_name()
    created_date = get_last_commit_date()
    build_date = get_build_date()
    symbol_ref = KICAD_CONFIG["symbol"]
    source_sql = "NULL" if SOURCE is None else f"'{SOURCE}'"

    sql_lines = [SQL_TEMPLATES["file_header"].format(
        datasheet_url=URL_TEMPLATES["datasheet"],
        symbol_ref=symbol_ref,
        script_name=script_name,
    )]

    total_parts = 0
    seen_unique_ids = set()
    current_family = None

    for series in SERIES_DATA:
        family = series["family"]
        if not is_family_enabled(family):
            continue

        # Section header when family changes
        if family != current_family:
            current_family = family
            family_names = {
                "LW": "LW Series - Double-sided ultra-low resistance",
                "BW": "BW Series - Double-sided low resistance (E24)",
                "CW": "CW Series - Double-sided low TCR",
                "BS_Q": "BS/Q Series - High power type",
                "RS_Q": "RS/Q Series - Standard type",
                "L": "L Series - Low TCR type",
            }
            sql_lines.append("")
            sql_lines.append(SQL_TEMPLATES["section_header"].format(
                section=family_names.get(family, family)))

        values = get_values_for_series(series)
        if not values:
            continue

        for tol_str in series["tolerances"]:
            if not is_tolerance_enabled(tol_str):
                continue

            tol_code = TOLERANCE_CODES[tol_str]

            for value_ohm in values:
                mpn = format_mpn(value_ohm, series, tol_code)
                unique_id = STRING_TEMPLATES["unique_id"].format(
                    manufacturer=MANUFACTURER, mpn=mpn)

                # Skip duplicates (can occur with overlapping TCR ranges)
                if unique_id in seen_unique_ids:
                    continue
                seen_unique_ids.add(unique_id)

                value_spice = encode_resistance_spice(value_ohm)
                description = STRING_TEMPLATES["description"].format(
                    manufacturer=MANUFACTURER,
                    composition=COMPOSITION.lower(),
                    value_readable=value_spice,
                    tolerance=tol_str,
                    power=series["power"],
                    tempco=series["tcr"],
                    package=series["package"],
                )
                part_locator = STRING_TEMPLATES["part_locator"].format(
                    composition_slug="thick-film",
                    value_lower=value_spice.lower(),
                    tolerance_lower=tol_str.lower(),
                    power_slug=series["power"].replace("/", "_").lower(),
                    package_lower=series["package"].lower(),
                )

                # All current-sense parts are tier 3 (specialty)
                part_tier = 3

                sql_line = SQL_TEMPLATES["insert"].format(
                    unique_id=unique_id,
                    part_locator=part_locator,
                    mpn=mpn,
                    manufacturer=MANUFACTURER,
                    variant="NULL",
                    package=series["package"],
                    value_sim=value_spice,
                    description=description,
                    datasheet=URL_TEMPLATES["datasheet"],
                    manufacturer_link=URL_TEMPLATES["manufacturer_link"],
                    kicad_symbol=symbol_ref,
                    kicad_footprint=get_kicad_footprint(series["package"]),
                    source=source_sql,
                    dump_priority=DUMP_PRIORITY,
                    tier=part_tier,
                    tags="passive,current-sense",
                    tolerance=tol_str,
                    power_rating=series["power"],
                    temp_coeff=series["tcr"],
                    voltage_rating="",
                    composition=COMPOSITION,
                    temp_operating_min=parse_temp_range(series["temp_operating"])[0],
                    temp_operating_max=parse_temp_range(series["temp_operating"])[1],
                    temp_storage_min=parse_temp_range(STRING_TEMPLATES["temp_storage"])[0],
                    temp_storage_max=parse_temp_range(STRING_TEMPLATES["temp_storage"])[1],
                    temp_soldering=parse_temp_single(STRING_TEMPLATES["temp_soldering"]),
                    sim_device=SIMULATION["device"],
                    sim_pins=SIMULATION["pins"],
                    lifecycle_status=LIFECYCLE_STATUS,
                    rohs=ROHS_COMPLIANT,
                    allow_substitution=ALLOW_SUBSTITUTION,
                    tracking=TRACKING,
                    created_at=created_date,
                    updated_at=build_date,
                    created_by=script_name,
                )
                sql_lines.append(sql_line)
                sql_lines.append(SQL_TEMPLATES["tag_insert"].format(
                    unique_id=unique_id, tag="passive"))
                sql_lines.append(SQL_TEMPLATES["tag_insert"].format(
                    unique_id=unique_id, tag="current-sense"))
                total_parts += 1

    sql_lines.append("")
    sql_lines.append(SQL_TEMPLATES["file_footer"].format(total_parts=total_parts))
    return "\n".join(sql_lines)


def main():
    """Generate current-sense resistor SQL based on configuration."""
    print("Panasonic ERJ Series Current-Sensing Resistor Generator")
    print("=" * 55)

    enabled_families = [f for f, v in FAMILY_ENABLE.items() if v.lower() == "yes"]
    enabled_tols = [t for t, v in TOLERANCE_ENABLE.items() if v.lower() == "yes"]
    print(f"\nEnabled families: {', '.join(enabled_families)}")
    print(f"Enabled tolerances: {', '.join(enabled_tols)}")

    # Count series entries per family
    for family in enabled_families:
        count = sum(1 for s in SERIES_DATA if s["family"] == family)
        print(f"  {family}: {count} range entries")

    sql_content = generate_resistors()

    if not sql_content:
        print("\nNo parts generated. Check configuration.")
        sys.exit(1)

    with open(OUTPUT_FILE, "w") as f:
        f.write(sql_content)

