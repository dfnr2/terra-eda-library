# E24 lookup table (IEC 60063 standard values, 1.0-9.1 decade)
E24_TABLE = [1.0, 1.1, 1.2, 1.3, 1.5, 1.6, 1.8, 2.0, 2.2, 2.4,
             2.7, 3.0, 3.3, 3.6, 3.9, 4.3, 4.7, 5.1, 5.6, 6.2,
             6.8, 7.5, 8.2, 9.1]


def get_script_name() -> str:
    return Path(__file__).name


def get_last_commit_date() -> str:
    try:
        result = subprocess.run(
            ["git", "log", "-1", "--format=%ci", __file__],
            capture_output=True, text=True, cwd=Path(__file__).parent,
        )
        if result.returncode == 0 and result.stdout.strip():
            parts = result.stdout.strip().split()
            return parts[0] + " " + parts[1]
    except Exception:
        pass
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def get_build_date() -> str:
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def get_kicad_footprint(package: str) -> str:
    metric = PACKAGE_METRIC.get(package, package)
    return f"{KICAD_CONFIG['footprint_prefix']}{package}_{metric}{KICAD_CONFIG['footprint_suffix']}"


def is_family_enabled(family: str) -> bool:
    return FAMILY_ENABLE.get(family, "no").lower() == "yes"


def is_tolerance_enabled(tol: str) -> bool:
    return TOLERANCE_ENABLE.get(tol, "no").lower() == "yes"


def generate_e24_milliohm_values(min_mohm: int, max_mohm: int) -> List[float]:
    """Generate E24 resistance values in a milliohm range, returning ohm values."""
    values = []
    for decade_exp in range(-2, 1):  # 0.01, 0.1, 1.0 decades
        for base in E24_TABLE:
            val_ohm = base * (10 ** decade_exp)
            val_mohm = round(val_ohm * 1000)
            if min_mohm <= val_mohm <= max_mohm:
                values.append(round(val_ohm, 6))
    return sorted(set(values))


def generate_e24_ohm_values(min_ohm: float, max_ohm: float) -> List[float]:
    """Generate E24 resistance values in an ohm range."""
    values = []
    for decade_exp in range(-1, 2):  # 0.1, 1.0, 10.0 decades
        for base in E24_TABLE:
            val = round(base * (10 ** decade_exp), 4)
            if min_ohm <= val <= max_ohm:
                values.append(val)
    return sorted(set(values))


def get_values_for_series(series: Dict) -> List[float]:
    """Get the list of resistance values (in ohms) for a series entry."""
    if "values" in series:
        return series["values"]
    elif "e24_min_mohm" in series:
        return generate_e24_milliohm_values(series["e24_min_mohm"], series["e24_max_mohm"])
    elif "e24_min" in series:
        return generate_e24_ohm_values(series["e24_min"], series["e24_max"])
    else:
        return []


# ======================== VALUE ENCODING ========================

# IEC/SPICE units for encode_resistance_spice
SPICE_UNITS = [
    ("m", -3),   # milli-ohm
    ("", 0),     # ohm
    ("K", 3),    # kilo-ohm
]


def encode_resistance_spice(value_ohm: float) -> str:
    """Encode resistance in SPICE format for the value field."""
    if value_ohm == 0:
        return "0"
    exp10 = math.log10(value_ohm)
    target = 3 * math.floor(exp10 / 3.0)
    marker, exp = min(SPICE_UNITS, key=lambda ue: abs(ue[1] - target))
    scale = 10 ** exp
    scaled = value_ohm / scale
    s = format(scaled, ".3f").rstrip("0").rstrip(".")
    return s + marker if marker else s


def encode_mpn_value_w(value_ohm: float) -> str:
    """Encode resistance for W-type MPNs (4-char, sub-ohm).

    Format: R + 3 digits representing milliohm with R as decimal.
    R005 = 5mΩ (0.005Ω), R047 = 47mΩ, R100 = 100mΩ
    """
    milliohm = round(value_ohm * 1000)
    return f"R{milliohm:03d}"


def encode_mpn_value_sq(value_ohm: float) -> str:
    """Encode resistance for SQ-type MPNs (3-char, IEC with R as decimal).

    Format: R as decimal point in ohm value.
    R10 = 0.10Ω, R22 = 0.22Ω, 1R0 = 1.0Ω, 9R1 = 9.1Ω
    """
    if value_ohm < 1.0:
        # Sub-ohm: R + 2 digits
        cents = round(value_ohm * 100)
        return f"R{cents:02d}"
    else:
        # 1Ω+: digit + R + digit
        whole = int(round(value_ohm, 1))
        frac = round((round(value_ohm, 1) - whole) * 10)
        return f"{whole}R{frac}"


def encode_mpn_value_l(value_ohm: float) -> str:
    """Encode resistance for L-type MPNs (3-char, milliohm with M marker).

    Format: milliohm value + M marker (for <100mΩ), or R{dd} for ≥100mΩ.
    20M = 20mΩ, 47M = 47mΩ, 50M = 50mΩ, R10 = 100mΩ (0.10Ω)
    """
    milliohm = round(value_ohm * 1000)
    if milliohm >= 100:
        # Use IEC ohm encoding: 100mΩ = 0.1Ω → R10
        cents = round(value_ohm * 100)
        return f"R{cents:02d}"
    else:
        return f"{milliohm:02d}M"


def format_mpn(value_ohm: float, series: Dict, tol_code: str) -> str:
    """Generate the full MPN for a part."""
    mpn_type = series["mpn_type"]
    erj_code = series["erj_code"]
    pkg = series["packaging"]

    if mpn_type == "W":
        value_code = encode_mpn_value_w(value_ohm)
        return f"ERJ{erj_code}{tol_code}{value_code}{pkg}"

    elif mpn_type == "SQ":
        range_letter = series["range_letter"]
        value_code = encode_mpn_value_sq(value_ohm)
        return f"ERJ{erj_code}{range_letter}{tol_code}{value_code}{pkg}"

    elif mpn_type == "L":
        value_code = encode_mpn_value_l(value_ohm)
        # L-series: ERJL{size}K{tol}{value}{pkg} where K = standard values
        size_code = erj_code[1:]  # Strip 'L' prefix → "03", "06", "14", "1D"
        return f"ERJL{size_code}K{tol_code}{value_code}{pkg}"

    raise ValueError(f"Unknown mpn_type: {mpn_type}")


