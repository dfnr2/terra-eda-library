"""Shared row writer for diodes_th generators.

Each run_*.py builds a list of dict rows (core + diodes-type columns) and calls write().
Rows are generated (source NULL, dump_priority 0, tier 2) and INSERTs name their columns.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]

# Package -> KiCad stock footprint (the one KiCad's Diode:<JEDEC> symbols name).
PKG = {
    "DO-35": "Diode_THT:D_DO-35_SOD27_P7.62mm_Horizontal",
    "DO-41": "Diode_THT:D_DO-41_SOD81_P10.16mm_Horizontal",
    "DO-201AD": "Diode_THT:D_DO-201AD_P15.24mm_Horizontal",
}

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "package", "value", "description",
    "datasheet", "manufacturer_link", "kicad_symbol", "kicad_footprint",
    "lifecycle_status", "rohs", "allow_substitution", "tracking", "created_by",
    "source", "dump_priority", "tier", "keywords", "pin_count",
    "temp_operating_min", "temp_operating_max", "temp_storage_min", "temp_storage_max",
    "diode_type", "voltage_rating", "forward_voltage", "forward_current",
    "current_rating", "power_rating",
]
GENERATED = {"source": None, "dump_priority": 0, "tier": 2}


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def check_datasheets(rows):
    for ds in sorted({r["datasheet"] for r in rows}):
        p = ROOT / ds.replace("${TERRA_EDA_LIB}/", "")
        if not p.exists():
            raise SystemExit(f"missing data sheet {p}")


def write(path, title, created_by, rows):
    ids = [r["unique_id"] for r in rows]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        raise SystemExit(f"duplicate unique_id: {dup}")
    for r in rows:
        unknown = set(r) - set(COLS)
        if unknown:
            raise SystemExit(f"{r['unique_id']}: unknown columns {sorted(unknown)}")
    lines = [f"-- Terra EDA Library - {title}",
             f"-- Generated by {created_by}. dump_priority=0: not dumped to static SQL.",
             "", "BEGIN TRANSACTION;", ""]
    for r in rows:
        r = {**r, **GENERATED}
        vals = ", ".join(sql(r.get(c)) for c in COLS)
        lines.append(f"INSERT INTO diodes_th ({', '.join(COLS)}) VALUES ({vals});")
    lines += ["", "COMMIT;", ""]
    Path(path).write_text("\n".join(lines))
    print(f"Generated {Path(path).name}: {len(rows)} rows")
