#!/usr/bin/env python3
"""onsemi MM5Z series Zener diodes — SOD-523, 500 mW, standard tolerance.

37 nominal voltages (2.4 V to 75 V) in one tolerance grade (~+/-5%), from the
"Electrical Characteristics - Standard Tolerance Series" table of datasheet
MM5Z2V4T1/D Rev. 19 (April 2025). MPN is MM5Z<code>T1G, where <code> is the
voltage code with a trailing V for whole volts (MM5Z5V1T1G, MM5Z18VT1G).

Per type: Vz min/max is VZ1 at IZT1 (5 mA for 2.4-24 V, 2 mA for 27-75 V);
impedance_max = ZZT at IZT; capacitance = C max at VR=0, 1 MHz.
VF = 0.9 V max at IF = 10 mA for all types. The datasheet gives no Izsm.

Not generated by default (toggles below):
  - 51-75 V types are marked "Contact Sales" in the datasheet.
  - T5G (8,000/reel) and SZMM5Z (AEC-Q101) orderables share the same specs;
    only the T1G (3,000/reel) commercial part is generated.

Same SOD-523 land as Nexperia BZX585 / Vishay BZX584C (shares their
part_locator per voltage).
"""
from pathlib import Path
from _zener_family import emit

# --- Configuration ---------------------------------------------------------
INCLUDE_CONTACT_SALES = False   # 51..75 V types ("Contact Sales")
REEL_SUFFIX = "T1G"             # "T5G" for the 8,000-piece reel
CONTACT_SALES = {"51", "56", "62", "68", "75"}

# code: (Vz_min, Vz_max, ZZT max ohms, C max pF)
DATA = {
    "2V4": (2.2, 2.6, 100, 450),
    "2V7": (2.5, 2.9, 100, 450),
    "3V0": (2.8, 3.2, 100, 450),
    "3V3": (3.1, 3.5, 95, 450),
    "3V6": (3.4, 3.8, 90, 450),
    "3V9": (3.7, 4.2, 90, 450),
    "4V3": (4.0, 4.6, 90, 450),
    "4V7": (4.4, 5.0, 80, 260),
    "5V1": (4.8, 5.4, 60, 225),
    "5V6": (5.2, 6.0, 40, 200),
    "6V2": (5.8, 6.6, 10, 185),
    "6V8": (6.4, 7.2, 15, 155),
    "7V5": (7.0, 7.9, 15, 140),
    "8V2": (7.7, 8.7, 15, 135),
    "9V1": (8.5, 9.6, 15, 130),
    "10": (9.4, 10.6, 20, 130),
    "11": (10.4, 11.6, 20, 130),
    "12": (11.4, 12.7, 25, 130),
    "13": (12.4, 14.1, 30, 120),
    "15": (14.3, 15.8, 30, 110),
    "16": (15.3, 17.1, 40, 105),
    "18": (16.8, 19.1, 45, 100),
    "20": (18.8, 21.2, 55, 85),
    "22": (20.8, 23.3, 55, 85),
    "24": (22.8, 25.6, 70, 80),
    "27": (25.1, 28.9, 80, 70),
    "30": (28.0, 32.0, 80, 70),
    "33": (31.0, 35.0, 80, 70),
    "36": (34.0, 38.0, 90, 70),
    "39": (37.0, 41.0, 130, 45),
    "43": (40.0, 46.0, 150, 40),
    "47": (44.0, 50.0, 170, 40),
    "51": (48.0, 54.0, 180, 40),
    "56": (52.0, 60.0, 200, 40),
    "62": (58.0, 66.0, 215, 35),
    "68": (64.0, 72.0, 240, 35),
    "75": (70.0, 79.0, 255, 35),
}


def _vz(code):
    return float(code.replace("V", ".")) if "V" in code else float(code)


def mpn_format(_letter, code):
    return f"MM5Z{code if 'V' in code else code + 'V'}{REEL_SUFFIX}"


TYPES = {}
for code, (vmin, vmax, zzt, cap) in DATA.items():
    if code in CONTACT_SALES and not INCLUDE_CONTACT_SALES:
        continue
    # Validate: nominal from the MPN code must sit inside the Vz window.
    if not vmin <= _vz(code) <= vmax:
        raise SystemExit(f"MM5Z{code}: nominal {_vz(code)} outside [{vmin}, {vmax}]")
    TYPES[code] = {
        "test_current": "5mA" if _vz(code) <= 24 else "2mA",
        "impedance_max": zzt,
        "capacitance": cap,
        "grades": {"C": [vmin, vmax]},
    }

if __name__ == "__main__":
    emit(
        Path(__file__).with_name("diodes_zener_generated_327_mm5z.sql"),
        Path(__file__).name,
        prefix="MM5Z", package="SOD-523",
        footprint="Diode_SMD:D_SOD-523", power_rating="500mW",
        forward_voltage="0.9V", manufacturer="onsemi", mpn_format=mpn_format,
        manufacturer_link="https://www.onsemi.com/products/discrete-power-modules/zener-diodes",
        datasheet="${TERRA_EDA_LIB}/datasheets/onsemi/mm5z2v4t1.pdf",
        extra_tags="small-signal", types=TYPES,
    )
