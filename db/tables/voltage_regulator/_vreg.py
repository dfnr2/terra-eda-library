"""Shared row writer and checks for the through-hole voltage_regulator generators.

Each run_3[1-9]0_*.py builds a list of dict rows (core + voltage_regulator columns)
and calls write(). Rows are generated (source NULL, dump_priority 0, tier 2) and
INSERTs name their columns.

Two checks run on every write():
- every datasheet path resolves to a parked PDF under datasheets/;
- every row's 3-pin datasheet pinout (``pinout``, e.g. "IN-GND-OUT" for pins 1-2-3)
  matches the pin names of the KiCad symbol it points at, so a symbol with a
  different pin map can never be borrowed silently. ``pinout`` is not a column.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
KICAD_SYMBOLS = Path("/usr/share/kicad/symbols")
TERRA_SYMBOLS = ROOT / "kicad_symbols"

TO220 = "Package_TO_SOT_THT:TO-220-3_Vertical"
TO92 = "Package_TO_SOT_THT:TO-92_Inline"
DIP14 = "Package_DIP:DIP-14_W7.62mm"

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "variant", "package", "value",
    "description", "datasheet", "manufacturer_link", "kicad_symbol", "kicad_footprint",
    "lifecycle_status", "rohs", "allow_substitution", "tracking", "created_by",
    "source", "dump_priority", "tier", "keywords", "pin_count",
    "temp_operating_min", "temp_operating_max",
    "regulator_type", "output_voltage", "output_voltage_min", "output_voltage_max",
    "output_current", "input_voltage_min", "input_voltage_max", "dropout_voltage",
    "quiescent_current", "output_noise", "psrr", "line_regulation", "load_regulation",
    "accuracy", "adjustable", "features",
]
DEFAULTS = {"lifecycle_status": "Active", "rohs": "Yes", "allow_substitution": "No",
            "tracking": "No"}
GENERATED = {"source": None, "dump_priority": 0, "tier": 2}

# Symbol pin names -> datasheet role.
ROLE = {"VI": "IN", "IN": "IN", "VIN": "IN", "VO": "OUT", "OUT": "OUT", "VOUT": "OUT",
        "GND": "GND", "ADJ": "ADJ"}


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def tol(lo, hi, nom):
    """Initial accuracy from the datasheet's 25 degC output limits, e.g. '±4% (4.8-5.2V at 25°C)'."""
    pct = round((abs(hi) - abs(lo)) / 2 / abs(nom) * 100, 1)
    pct = f"{pct:g}"
    return f"±{pct}% ({lo:g} to {hi:g}V at 25°C)"


def _symbol_pins(lib_id):
    """Return {pin_number: role} for a KiCad symbol, following `extends`, or None if not found."""
    nick, name = lib_id.split(":", 1)
    path = (TERRA_SYMBOLS / f"{nick}.kicad_sym") if nick.startswith("terra_") \
        else (KICAD_SYMBOLS / f"{nick}.kicad_sym")
    if not path.exists():
        return None
    txt = path.read_text()
    starts = [m.start() for m in re.finditer(r'\n\t\(symbol "', txt)] + [len(txt)]
    blocks = {}
    for a, b in zip(starts, starts[1:]):
        chunk = txt[a:b]
        n = re.match(r'\n\t\(symbol "([^"]+)"', chunk).group(1)
        ext = re.search(r'\(extends "([^"]+)"\)', chunk)
        pins = re.findall(r'\(pin \w+ \w+.*?\(name "([^"]*)".*?\(number "([^"]*)"', chunk, re.S)
        blocks[n] = (ext.group(1) if ext else None, pins)
    if name not in blocks:
        return {}
    ext, pins = blocks[name]
    while not pins and ext:
        ext, pins = blocks[ext]
    return {num: ROLE.get(nm.upper(), nm.upper()) for nm, num in pins}


def check_pinouts(rows):
    if not KICAD_SYMBOLS.exists():
        print("  (stock KiCad symbols not installed; pinout check skipped)")
        return
    for r in rows:
        want = r.get("pinout")
        if not want or not r.get("kicad_symbol"):
            continue
        got = _symbol_pins(r["kicad_symbol"])
        if got is None:
            raise SystemExit(f"{r['unique_id']}: symbol library for {r['kicad_symbol']} not found")
        if not got:
            raise SystemExit(f"{r['unique_id']}: symbol {r['kicad_symbol']} not found")
        expect = dict(zip(("1", "2", "3"), want.split("-")))
        if got != expect:
            raise SystemExit(f"{r['unique_id']}: {r['kicad_symbol']} pins {got} != datasheet {expect}")


def check_datasheets(rows):
    for ds in sorted({r["datasheet"] for r in rows}):
        p = ROOT / ds.replace("${TERRA_EDA_LIB}/", "")
        if not p.exists():
            raise SystemExit(f"missing datasheet {p}")


def write(path, title, created_by, rows):
    ids = [r["unique_id"] for r in rows]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        raise SystemExit(f"duplicate unique_id: {dup}")
    for r in rows:
        unknown = set(r) - set(COLS) - {"pinout"}
        if unknown:
            raise SystemExit(f"{r['unique_id']}: unknown columns {sorted(unknown)}")
    check_datasheets(rows)
    check_pinouts(rows)
    lines = [f"-- Terra EDA Library - {title}",
             f"-- Generated by {created_by}. dump_priority=0: not dumped to static SQL.",
             "", "BEGIN TRANSACTION;", ""]
    review = []
    for r in rows:
        r = {**DEFAULTS, **r, **GENERATED, "created_by": created_by}
        if not r.get("kicad_symbol") or not r.get("kicad_footprint"):
            review.append(r["unique_id"])
        vals = ", ".join(sql(r.get(c)) for c in COLS)
        lines.append(f"INSERT INTO voltage_regulator ({', '.join(COLS)}) VALUES ({vals});")
    lines += ["", "COMMIT;", ""]
    Path(path).write_text("\n".join(lines))
    print(f"Generated {Path(path).name}: {len(rows)} rows")
    for uid in review:
        print(f"  REVIEW (NULL symbol/footprint): {uid}")
