#!/usr/bin/env python3
"""Bare-pad test points: a copper pad on the board with no component fitted.

Two rows, one per KiCad stock footprint, sharing the stock Connector:TestPoint symbol:
a 1.0 mm THT pad with 0.5 mm via/drill (replaces hotwire:TP via 1mm on the cartridge) and
a plain 1.0 mm SMT pad. No MPN or datasheet exists, so mpn is a descriptive name, and
exclude_from_bom is set because nothing is purchased.

Generated output (dump_priority=0, source=NULL) is not dumped to static SQL.
"""
from pathlib import Path

OUTPUT_FILE = Path(__file__).with_name("test_points_generated_310_bare_pads.sql")
CREATED_BY = Path(__file__).name

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "value", "description",
    "kicad_symbol", "kicad_footprint", "exclude_from_bom", "allow_substitution",
    "tracking", "source", "dump_priority", "tier", "keywords", "pin_count",
    "tp_style", "pad_diameter_mm", "mount", "created_by",
]

COMMON = {
    "manufacturer": "Generic", "value": "Test Point",
    "kicad_symbol": "Connector:TestPoint", "exclude_from_bom": 1,
    "allow_substitution": "No", "tracking": "No", "source": None,
    "dump_priority": 0, "tier": 2, "pin_count": "1", "pad_diameter_mm": 1.0,
    "created_by": CREATED_BY,
}

PARTS = [
    {**COMMON, "unique_id": "Generic-TP-PAD-D1.0-THT", "mpn": "TP-PAD-D1.0-THT",
     "part_locator": "testpoint-bare-pad-tht-d1.0",
     "description": "Bare test pad, 1.0 mm round with 0.5 mm drill/via, no component fitted",
     "kicad_footprint": "TestPoint:TestPoint_THTPad_D1.0mm_Drill0.5mm",
     "keywords": "test,point,testpoint,test-point,bare-pad,pad,via,tht,no-component",
     "tp_style": "thru-hole", "mount": "THT"},
    {**COMMON, "unique_id": "Generic-TP-PAD-D1.0-SMT", "mpn": "TP-PAD-D1.0-SMT",
     "part_locator": "testpoint-bare-pad-smt-d1.0",
     "description": "Bare test pad, 1.0 mm round SMT, no component fitted",
     "kicad_footprint": "TestPoint:TestPoint_Pad_D1.0mm",
     "keywords": "test,point,testpoint,test-point,bare-pad,pad,smt,no-component",
     "tp_style": "pad", "mount": "SMT"},
]


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    ids = [p["unique_id"] for p in PARTS]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate unique_id")
    lines = ["-- Terra EDA Library - bare-pad test points",
             f"-- Generated by {CREATED_BY}.", "", "BEGIN TRANSACTION;", ""]
    for p in PARTS:
        vals = ", ".join(sql(p.get(c)) for c in COLS)
        lines.append(f"INSERT INTO test_points ({', '.join(COLS)}) VALUES ({vals});")
    lines += ["", "COMMIT;", ""]
    OUTPUT_FILE.write_text("\n".join(lines))
    print(f"Generated {OUTPUT_FILE.name}: {len(PARTS)} parts")


if __name__ == "__main__":
    main()
