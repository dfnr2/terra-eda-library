#!/usr/bin/env python3
"""Murata BLM18 GHz-noise chip ferrite beads (0603 / 1608Metric).

Covers the series outside the N1 spec that run_500 generates: BLM18EG (low DC
resistance, high current; SN1 and thin TN1) from JENF243A_0021U-01, and
BLM18HE / HG / HD / HB / HK from JENF243A_0004W-01. Data transcribed from those
specs into murata_blm18_ghz_catalog.json (one entry per part, D = 180mm tape).

Rated current follows run_500's convention: the headline figure is the 85 C
rating where the spec derates (2000 mA -> 1000 mA at 125 C), else the flat
rating. Generated output (dump_priority=0, source=NULL) is not dumped to static
SQL.
"""
import json
from pathlib import Path

OUTPUT_FILE = Path(__file__).with_name("ferrites_smt_generated_501_murata_blm18_ghz.sql")
CATALOG_FILE = Path(__file__).with_name("murata_blm18_ghz_catalog.json")
CREATED_BY = Path(__file__).name

MANUFACTURER = "Murata"
PACKAGE = "0603"
SYMBOL = "Device:FerriteBead_Small"
FOOTPRINT = "Inductor_SMD:L_0603_1608Metric"
DATASHEET = {
    "EG": "${TERRA_EDA_LIB}/datasheets/murata/blm18eg-ghz.pdf",
    "H": "${TERRA_EDA_LIB}/datasheets/murata/blm18h-ghz.pdf",
}

# Series code -> Murata application classification.
APPLICATION = {
    "EG": "GHz general use, low DCR",
    "HE": "GHz DC power line",
    "HG": "GHz general use",
    "HD": "GHz high-speed signal line",
    "HB": "GHz high-speed signal line",
    "HK": "GHz digital interface",
}

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "package", "value",
    "description", "datasheet", "manufacturer_link", "kicad_symbol",
    "kicad_footprint", "lifecycle_status", "rohs", "allow_substitution",
    "tracking", "source", "dump_priority", "tier", "keywords", "pin_count",
    "temp_operating_min", "temp_operating_max", "temp_storage_min",
    "temp_storage_max", "impedance_at_freq", "dc_resistance", "current_rating",
    "tolerance",
]


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def row(p):
    mpn, series = p["mpn"], p["series"]
    z = p["impedance_nominal_ohm"]
    r85, r125 = p["rated_ma_85c"], p["rated_ma_125c"]
    rated = r85 if r85 is not None else r125
    imax = (f"Imax={r85}mA(85°C)/{r125}mA(125°C)"
            if r85 is not None else f"Imax={r125}mA")
    tol = p["impedance_spec"].split("±")[1] if "±" in p["impedance_spec"] else None
    thin = ", thin 0.5mm" if mpn[10:12] == "TN" else ""
    rec = {
        "unique_id": f"{MANUFACTURER}-{mpn}",
        "part_locator": f"ferrite-bead-{z}r-{rated}ma-0603",
        "mpn": mpn, "manufacturer": MANUFACTURER, "package": PACKAGE,
        "value": f"{z}Ω {rated}mA",
        "description": (f"Murata {mpn} chip ferrite bead, {z}Ω@100MHz {tol}, "
                        f"{p['impedance_ghz']}, {imax}, DCRmax={p['dcr_max_ohm']}Ω, "
                        f"{APPLICATION[series]}, 0603{thin}"),
        "datasheet": DATASHEET["EG" if series == "EG" else "H"],
        "manufacturer_link": f"https://www.murata.com/en-us/products/productdetail?partno={mpn[:-1]}%23",
        "kicad_symbol": SYMBOL, "kicad_footprint": FOOTPRINT,
        "lifecycle_status": p["lifecycle_status"],
        "rohs": "Yes", "allow_substitution": "No", "tracking": "No",
        "source": None, "dump_priority": 0, "tier": 2,
        "keywords": "ferrite,bead,ghz", "pin_count": "2",
        "temp_operating_min": float(p["temp_operating_min"]),
        "temp_operating_max": float(p["temp_operating_max"]),
        "temp_storage_min": -55.0, "temp_storage_max": 125.0,
        "impedance_at_freq": f"{z}Ω@100MHz",
        "dc_resistance": f"{p['dcr_max_ohm']}Ω", "current_rating": f"{rated}mA",
        "tolerance": tol,
    }
    vals = ", ".join(sql(rec[c]) for c in COLS)
    return f"INSERT INTO ferrites_smt ({', '.join(COLS)}) VALUES ({vals});"


def main():
    parts = json.loads(CATALOG_FILE.read_text())["parts"]
    seen = set()
    for p in parts:
        if p["mpn"] in seen:
            raise SystemExit(f"duplicate mpn {p['mpn']}")
        seen.add(p["mpn"])
    lines = [
        "-- Terra EDA Library - Murata BLM18 GHz-noise chip ferrite beads (EG, H*)",
        f"-- Datasheet-driven (JENF243A_0021U-01, JENF243A_0004W-01). Generated by {CREATED_BY}.",
        "-- dump_priority=0, source=NULL: regenerated, not dumped to static SQL.",
        "",
        "BEGIN TRANSACTION;",
        "",
    ]
    lines += [row(p) for p in parts]
    lines += ["", "COMMIT;", ""]
    OUTPUT_FILE.write_text("\n".join(lines))
    print(f"Generated {OUTPUT_FILE.name}: {len(parts)} parts")


if __name__ == "__main__":
    main()
