CREATE TABLE ic_nvram (
    unique_id TEXT PRIMARY KEY,
    part_locator TEXT,
    mpn TEXT NOT NULL,
    manufacturer TEXT NOT NULL,
    variant TEXT,
    package TEXT,
    value TEXT,
    description TEXT,
    datasheet TEXT,
    manufacturer_link TEXT,
    kicad_symbol TEXT,
    kicad_footprint TEXT,
    altium_symbol TEXT,
    altium_footprint TEXT,
    lifecycle_status TEXT DEFAULT 'Active',
    rohs TEXT DEFAULT 'no',
    rohs_document_link TEXT,
    allow_substitution TEXT DEFAULT 'no',
    tracking TEXT DEFAULT 'no',
    standards_version TEXT DEFAULT 'v1.0',
    bom_comment TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    created_by TEXT,
    source TEXT DEFAULT 'static',
    dump_priority INTEGER DEFAULT 1,
    tier INTEGER DEFAULT 2,
    keywords TEXT DEFAULT '',
    sim_model_type TEXT,
    sim_device TEXT,
    sim_pins TEXT,
    sim_model_file TEXT,
    sim_params TEXT,
    pin_count TEXT,
    component_height TEXT,
    exclude_from_bom BOOLEAN NOT NULL DEFAULT 0,
    temp_operating_min REAL,
    temp_operating_max REAL,
    temp_storage_min REAL,
    temp_storage_max REAL,
    temp_soldering REAL,
    capacity TEXT,                -- total bits, ic_memory format ('256 Kbit'),
    word_size TEXT,               -- '8-bit',
    speed TEXT,                   -- read access time ('70 ns'),
    supply_voltage_min REAL,      -- VCC min (V); with max, encodes the 5%/10% grade,
    supply_voltage_max REAL,      -- VCC max (V),
    persistence_years TEXT,       -- data retention without VCC, as in ic_memory,
    write_protect_voltage TEXT,   -- VTP, the VCC level that write-protects the RAM,
    battery TEXT,                 -- 'integrated lithium' | 'SNAPHAT (replaceable)',
    sram_socket TEXT,             -- JEDEC SRAM it drops into: '6116', '6264', '62256'...,
    rtc TEXT                      -- 'Yes' for timekeeper parts, else 'No'
);
