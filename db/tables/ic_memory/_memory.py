"""Shared row builder and SQL writer for the vintage parallel-memory generators.

Each ``run_3x0_*.py`` family script transcribes its data book's ordering tables and
calls ``row()`` once per ordering code, then ``write()``. Keeping the column list and
the defaults here keeps the SRAM, DRAM, EPROM, EEPROM and PROM families consistent.
"""
from pathlib import Path

COLS = [
    "unique_id", "part_locator", "mpn", "manufacturer", "package", "value",
    "description", "datasheet", "manufacturer_link", "kicad_symbol", "kicad_footprint",
    "lifecycle_status", "rohs", "allow_substitution", "tracking", "standards_version",
    "created_by", "source", "dump_priority", "tier", "keywords", "pin_count",
    "temp_operating_min", "temp_operating_max",
    "memory_type", "capacity", "word_size", "speed", "interface",
    "persistence_cycles", "persistence_years", "supply_rails", "programming_voltage",
]

DS_ROOT = "${TERRA_EDA_LIB}/datasheets"


def capacity(words, bits):
    """'1Kx4' style organization -> ('4 Kbit', '4-bit'), matching the existing rows."""
    total = words * bits
    if total % (1024 * 1024) == 0:
        cap = f"{total // (1024 * 1024)} Mbit"
    elif total % 1024 == 0:
        cap = f"{total // 1024} Kbit"
    else:
        cap = f"{total} bit"
    return cap, f"{bits}-bit"


def org(words, bits):
    """Organization as printed in descriptions and keywords: 1Kx4, 256x4, 32Kx8."""
    w = f"{words // 1024}K" if words >= 1024 and words % 1024 == 0 else str(words)
    return f"{w}x{bits}"


def footprint(pins, width_in):
    """Stock DIP land pattern for the row spacing the package outline gives."""
    mm = {0.3: "7.62", 0.4: "10.16", 0.6: "15.24"}[width_in]
    return f"Package_DIP:DIP-{pins}_W{mm}mm"


def row(*, created_by, manufacturer, mpn, value, memory_type, words, bits, speed,
        package, pins, width_in, symbol, datasheet, description, keywords,
        supply_rails, lifecycle="Obsolete", rohs="No", mfr_link=None,
        temp=(0, 70), programming_voltage=None, cycles=None, years=None,
        locator_type=None):
    cap, word = capacity(words, bits)
    o = org(words, bits)
    kind = (locator_type or memory_type).lower().replace(" ", "-")
    return {
        "unique_id": f"{manufacturer}-{mpn}",
        "part_locator": f"mem-{kind}-{o.lower()}-dip{pins}",
        "mpn": mpn, "manufacturer": manufacturer, "package": package, "value": value,
        "description": description,
        "datasheet": f"{DS_ROOT}/{datasheet}", "manufacturer_link": mfr_link,
        "kicad_symbol": symbol, "kicad_footprint": footprint(pins, width_in),
        "lifecycle_status": lifecycle, "rohs": rohs,
        "allow_substitution": "Yes", "tracking": "No", "standards_version": "1.0",
        "created_by": created_by, "source": None, "dump_priority": 0, "tier": 2,
        "keywords": ", ".join(dict.fromkeys([value, o] + keywords)),
        "pin_count": str(pins),
        "temp_operating_min": temp[0], "temp_operating_max": temp[1],
        "memory_type": memory_type, "capacity": cap, "word_size": word,
        "speed": speed, "interface": "parallel",
        "persistence_cycles": cycles, "persistence_years": years,
        "supply_rails": supply_rails, "programming_voltage": programming_voltage,
    }


def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def write(output_file, title, created_by, recs):
    """Write the INSERTs, failing on a duplicate unique_id rather than dropping rows."""
    ids = [r["unique_id"] for r in recs]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit(f"duplicate unique_id: {dupes}")
    lines = [
        f"-- Terra EDA Library - ic_memory {title}",
        f"-- Generated by {created_by}. dump_priority=0, source=NULL: not dumped to static SQL.",
        "",
        "BEGIN TRANSACTION;",
        "",
    ]
    for r in recs:
        vals = ", ".join(sql(r.get(c)) for c in COLS)
        lines.append(f"INSERT INTO ic_memory ({', '.join(COLS)}) VALUES ({vals});")
    lines += ["", "COMMIT;", ""]
    Path(output_file).write_text("\n".join(lines))
    print(f"Generated {Path(output_file).name}: {len(recs)} parts")
