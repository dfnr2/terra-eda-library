CREATE TABLE relays_ssr (
    unique_id TEXT PRIMARY KEY,
    part_locator TEXT,
    mpn TEXT NOT NULL,
    manufacturer TEXT NOT NULL,
    variant TEXT,
    package TEXT,
    value TEXT,
    description TEXT,
    datasheet TEXT,
    manufacturer_link TEXT,
    kicad_symbol TEXT,
    kicad_footprint TEXT,
    altium_symbol TEXT,
    altium_footprint TEXT,
    lifecycle_status TEXT DEFAULT 'Active',
    rohs TEXT DEFAULT 'no',
    rohs_document_link TEXT,
    allow_substitution TEXT DEFAULT 'no',
    tracking TEXT DEFAULT 'no',
    standards_version TEXT DEFAULT 'v1.0',
    bom_comment TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    created_by TEXT,
    source TEXT DEFAULT 'static',
    dump_priority INTEGER DEFAULT 1,
    tier INTEGER DEFAULT 2,
    keywords TEXT DEFAULT '',
    sim_model_type TEXT,
    sim_device TEXT,
    sim_pins TEXT,
    sim_model_file TEXT,
    sim_params TEXT,
    pin_count TEXT,
    component_height TEXT,
    exclude_from_bom BOOLEAN NOT NULL DEFAULT 0,
    temp_operating_min REAL,
    temp_operating_max REAL,
    temp_storage_min REAL,
    temp_storage_max REAL,
    temp_soldering REAL,
    contact_form TEXT,          -- 1 Form A | 1 Form B | 2 Form A | 2 Form B | 1 Form C | 1 Form A + 1 Form B,
    channels INTEGER,           -- independent switches per package,
    load_type TEXT,             -- AC/DC | DC,
    voltage_rating TEXT,        -- max load (off-state) voltage, peak AC/DC,
    current_rating TEXT,        -- max continuous load current,
    on_resistance TEXT,         -- Ron max, with condition,
    off_capacitance TEXT,       -- Coff typ, where specified,
    led_operate_current TEXT,   -- max LED current needed to turn on (I_Fon),
    led_forward_voltage TEXT,   -- LED Vf, with condition,
    control_voltage TEXT,       -- input range for voltage-driven modules (no LED input),
    isolation_voltage TEXT,     -- I/O isolation, e.g. 5000Vrms,
    turn_on_time TEXT,          -- t_on max,
    turn_off_time TEXT          -- t_off max
);
