CREATE TABLE dc_dc_converters (
    unique_id TEXT PRIMARY KEY,
    part_locator TEXT,
    mpn TEXT NOT NULL,
    manufacturer TEXT NOT NULL,
    variant TEXT,
    package TEXT,
    value TEXT,
    description TEXT,
    datasheet TEXT,
    manufacturer_link TEXT,
    kicad_symbol TEXT,
    kicad_footprint TEXT,
    altium_symbol TEXT,
    altium_footprint TEXT,
    lifecycle_status TEXT DEFAULT 'Active',
    rohs TEXT DEFAULT 'no',
    rohs_document_link TEXT,
    allow_substitution TEXT DEFAULT 'no',
    tracking TEXT DEFAULT 'no',
    standards_version TEXT DEFAULT 'v1.0',
    bom_comment TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    created_by TEXT,
    source TEXT DEFAULT 'static',
    dump_priority INTEGER DEFAULT 1,
    tier INTEGER DEFAULT 2,
    keywords TEXT DEFAULT '',
    sim_model_type TEXT,
    sim_device TEXT,
    sim_pins TEXT,
    sim_model_file TEXT,
    sim_params TEXT,
    pin_count TEXT,
    component_height TEXT,
    exclude_from_bom BOOLEAN NOT NULL DEFAULT 0,
    temp_operating_min REAL,
    temp_operating_max REAL,
    temp_storage_min REAL,
    temp_storage_max REAL,
    temp_soldering REAL,
    input_voltage_nominal REAL,  -- nominal input (V),
    input_voltage_min REAL,      -- operating input range, low (V),
    input_voltage_max REAL,      -- operating input range, high (V),
    output_config TEXT,          -- 'single' | 'dual' (dual = +/-V about a common),
    output_voltage REAL,         -- magnitude of each output rail (V),
    output_current REAL,         -- max current per rail (A),
    output_power REAL,           -- max total output power (W),
    isolated TEXT,               -- 'yes' | 'no',
    isolation_voltage REAL,      -- input-to-output rating, 1 minute (Vdc),
    regulated TEXT,              -- 'yes' | 'no',
    efficiency REAL,             -- typical efficiency at full load (%),
    ripple_noise REAL            -- max ripple and noise (mVp-p)
);
